export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, className }: { name: IconName; className?: string }) {
  return (
    <svg className={className ? `pixel-icon ${className}` : 'pixel-icon'} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden="true">
      {ICONS[name].flatMap((row, y) => [...row].map((pixel, x) => (pixel === '1' ? <rect key={`${x},${y}`} x={x} y={y} width="1" height="1" /> : null)))}
    </svg>
  );
}
